  function viewSearch() {
    const frag = document.createDocumentFragment();
    frag.append(el('div', { class: 'page-head' }, el('div', null, el('h1', { class: 'page-title' }, t('search')))));
    const host = el('div');
    frag.append(searchBox(state.q, (v) => { state.q = v; writeHash(); renderResults(); }, true), host);
    const now = confNow();

    function renderResults() {
      host.innerHTML = '';
      const q = norm(state.q);
      if (q.length < 2) { host.append(speakerIndex()); return; }
      const talks = Object.values(D.talks).filter(tk => norm(`${tk.title} ${tk.first} ${tk.last} ${tk.org} ${tk.id} ${tk.number}`).includes(q))
        .sort((a, b) => (a.date || '9').localeCompare(b.date || '9') || (a.start || '').localeCompare(b.start || ''));
      const posters = D.posters.filter(p => norm(`${p.title} ${p.first} ${p.last} ${p.org} ${p.id}`).includes(q));
      const total = talks.length + posters.length;
      host.append(el('p', { class: 'result-count' }, total ? `${t('results')}: ${total}` : t('nothingFound')));
      if (!total) return;
      const byDay = new Map();
      for (const tk of talks) { const k = tk.date || 'none'; if (!byDay.has(k)) byDay.set(k, []); byDay.get(k).push(tk); }
      for (const [date, list] of byDay) {
        const group = el('section', { class: 'group' });
        group.append(el('div', { class: 'group-head' }, el('h3', null, date === 'none' ? t('noTalks') : fmtLong(date))));
        const card = el('div', { class: 'card' });
        for (const tk of list) {
          const b = tk.blockId ? blocksById[tk.blockId] : null;
          const ctx = tk.section === 'P' ? talkKicker(tk) : `${t('section')} ${tk.section}${b && roomOf(b) ? ` · ${t('room')} ${roomOf(b)}` : ''}`;
          card.append(renderTalkRow(tk, now.date === date ? now : null, { q, context: ctx, colored: true }));
        }
        group.append(card); host.append(group);
      }
      if (posters.length) {
        const group = el('section', { class: 'group' });
        group.append(el('div', { class: 'group-head' }, el('h3', null, t('posters')), posterBlock ? el('span', { class: 'when' }, `${fmtShort(posterBlock.date)}, ${posterBlock.start}–${posterBlock.end}`) : null));
        const list = el('div', { class: 'poster-list' });
        for (const p of posters) list.append(renderPoster(p, q));
        group.append(list); host.append(group);
      }
    }
    function speakerIndex() {
      const people = new Map();
      const add = (x) => { const key = norm(`${x.last}|${x.first}`); if (!people.has(key)) people.set(key, { last: x.last, first: x.first, n: 0 }); people.get(key).n++; };
      Object.values(D.talks).forEach(add); D.posters.forEach(add);
      const list = Array.from(people.values()).filter(p => p.last).sort((a, b) => a.last.localeCompare(b.last, locale()) || a.first.localeCompare(b.first, locale()));
      const byLetter = new Map();
      for (const p of list) { const ch = p.last[0].toUpperCase(); if (!byLetter.has(ch)) byLetter.set(ch, []); byLetter.get(ch).push(p); }
      const wrap = el('div', { class: 'index' });
      wrap.append(el('h2', { class: 'small muted', style: 'text-transform:uppercase;letter-spacing:.08em;font-weight:700' }, `${t('speakerIndex')} · ${list.length}`));
      const letters = Array.from(byLetter.keys()).sort((a, b) => a.localeCompare(b, locale()));
      for (const ch of letters) {
        wrap.append(el('div', { class: 'index-letter' }, el('div', { class: 'letter', 'aria-hidden': 'true' }, ch), el('div', { class: 'index-names' },
          ...byLetter.get(ch).map(p => el('button', { class: 'name-chip', type: 'button', onclick: () => { const q = speakerName(p); state.q = q; $('.search-box input').value = q; $('.search-box .clear').hidden = false; writeHash(); renderResults(); } }, speakerName(p) || p.last, p.n > 1 ? el('span', { class: 'n' }, `×${p.n}`) : null)))));
      }
      return wrap;
    }
    renderResults();
    return frag;
  }

