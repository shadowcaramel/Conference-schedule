  function mergeDayBands(date) {
    const hit = bandsByDate.get(date);
    if (hit) return hit;
    const blocks = blocksOn(date).slice().sort((a, b) => a.start.localeCompare(b.start) || a.type.localeCompare(b.type));
    const bands = [];
    let i = 0;
    while (i < blocks.length) {
      const b = blocks[i];
      if (TALK_LIKE.has(b.type)) {
        const start = b.start; let end = b.end; const items = [b]; i++;
        while (i < blocks.length && TALK_LIKE.has(blocks[i].type)) {
          items.push(blocks[i]); if (blocks[i].end > end) end = blocks[i].end; i++;
        }
        bands.push({ start, end, kind: 'plenary', items });
      } else if (b.type === 'section') {
        bands.push({ start: b.start, end: b.end, kind: 'section', items: [b] });
        i++;
      } else {
        bands.push({ start: b.start, end: b.end, kind: b.type, items: [b] });
        i++;
      }
    }
    bandsByDate.set(date, bands);
    return bands;
  }

  function overviewTicks(byDay) {
    const mins = new Set();
    for (const d of DAYS) {
      for (const b of byDay[d] || []) {
        mins.add(toMin(b.start));
        mins.add(toMin(b.end));
      }
    }
    return Array.from(mins).sort((a, b) => a - b);
  }

  function overviewSectionRank(band) {
    if (OVERVIEW_SECTION_SORT !== 'room') {
      return Number(band.items[0] && band.items[0].section) || 99;
    }
    const room = roomOf(band.items[0]) || '';
    if (/библиотек|library/i.test(room)) return 0;
    if (/актов|assembly/i.test(room)) return 1;
    if (/117л/.test(room)) return 2;
    if (/315л/.test(room)) return 3;
    return 4;
  }
  function cmpOverviewSection(a, b) {
    const r = overviewSectionRank(a) - overviewSectionRank(b);
    if (r) return r;
    return String(a.items[0] && a.items[0].section).localeCompare(String(b.items[0] && b.items[0].section), undefined, { numeric: true });
  }
  function overviewSectionClusters(bands) {
    const sections = bands.filter(b => b.kind === 'section').slice().sort((a, b) => {
      const t = a.start.localeCompare(b.start);
      if (t) return t;
      return cmpOverviewSection(a, b);
    });
    const clusters = [];
    for (const band of sections) {
      const start = toMin(band.start);
      const end = toMin(band.end);
      const last = clusters[clusters.length - 1];
      if (last && start < last.end) {
        last.items.push(band);
        if (end > last.end) last.end = end;
      } else {
        clusters.push({ start, end, items: [band] });
      }
    }
    for (const cl of clusters) cl.items.sort(cmpOverviewSection);
    return clusters;
  }

